"""Regenerate docs/tools.md from the live tool definitions (names, descriptions, parameters).

Run from the repository root:  uv run python scripts/generate_tool_docs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import anyio
from mcp import Client

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tests.fakes import FakeYouTubeAPI  # noqa: E402

from youtube_studio_mcp.config import Settings  # noqa: E402
from youtube_studio_mcp.server import build_server  # noqa: E402

DESTINATION = ROOT / "docs" / "tools.md"
GROUPS = [
    ("Account", ["get_auth_status", "authenticate"]),
    (
        "Channel & content",
        ["get_channel", "list_videos", "get_videos_details", "list_playlists", "list_comments"],
    ),
    (
        "Analytics",
        [
            "get_performance_summary",
            "get_metrics_over_time",
            "get_top_videos",
            "get_audience_breakdown",
            "get_traffic_sources",
            "get_audience_retention",
            "get_revenue",
            "query_analytics",
        ],
    ),
    ("Impressions & CTR (beta)", ["enable_impressions_reports", "get_impressions"]),
    ("Media kit & charts", ["get_media_kit_data", "create_chart"]),
    ("Write tools (opt-in)", ["update_video_details", "reply_to_comment", "moderate_comments"]),
]


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " \\| ".join(parts) + (
            " \\| null" if any(s.get("type") == "null" for s in schema["anyOf"]) else ""
        )
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    return str(schema.get("type", "any"))


def _default(schema: dict[str, Any], required: bool) -> str:
    if required:
        return "**required**"
    if "default" not in schema:
        return ""
    return f"`{json.dumps(schema['default'])}`"


def _escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render(tools: list[Any]) -> str:
    by_name = {tool.name: tool for tool in tools}
    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/generate_tool_docs.py from the tool definitions. Do not edit by hand. -->",
        "",
        "Every tool returns JSON. Dates are US Pacific time; percentages are 0-100. Read-only tools are",
        "annotated `readOnlyHint: true` so clients can auto-approve them.",
        "",
    ]
    for group, names in GROUPS:
        lines += [f"## {group}", ""]
        for name in names:
            tool = by_name[name]
            hints = tool.annotations
            if hints and hints.read_only_hint:
                badge = "read-only"
            elif group.startswith("Write tools"):
                badge = "**changes your channel** (opt-in)"
            else:
                badge = "has side effects (no channel changes)"
            lines += [f"### `{name}`", "", f"*{tool.title or name}* · {badge}", ""]
            lines += [
                " ".join(line.strip() for line in (tool.description or "").splitlines() if line.strip()),
                "",
            ]
            properties = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            if properties:
                lines += ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
                for param, schema in properties.items():
                    lines.append(
                        f"| `{param}` | {_type(schema)} | {_default(schema, param in required)} | "
                        f"{_escape(schema.get('description', ''))} |"
                    )
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


async def collect() -> list[Any]:
    settings = Settings(config_dir=ROOT / ".docs-config", output_dir=ROOT / ".docs-out", enable_write=True)
    async with Client(build_server(settings, api=FakeYouTubeAPI())) as client:
        return list((await client.list_tools()).tools)


def main() -> None:
    DESTINATION.write_text(render(anyio.run(collect)), encoding="utf-8")
    print(f"Wrote {DESTINATION.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
